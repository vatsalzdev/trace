import { readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const file = process.argv[2];
if (!file) {
  console.error('usage: npm run blocklist:import <domains.txt>');
  process.exit(1);
}

const DOMAIN_RE = /^(?=.{4,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;
const domains = new Set<string>();
for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
  const value = line.trim().toLowerCase();
  if (!value || value.startsWith('#') || value.startsWith('!')) continue;
  const host = value.replace(/^https?:\/\//, '').split('/')[0].split(':')[0].replace(/^www\./, '');
  if (DOMAIN_RE.test(host)) domains.add(host);
}

const sorted = [...domains].sort();
const source = basename(file);
const out = [
  '// Generated by `npm run blocklist:import <file>`. Do not edit by hand.',
  `export const BLOCKLIST_SOURCE = ${JSON.stringify(source)};`,
  `export const BLOCKLIST: string[] = ${JSON.stringify(sorted, null, 2)};`,
  '',
].join('\n');
writeFileSync(join('shared', 'blocklist.ts'), out, 'utf8');
console.log(`Imported ${sorted.length} domain${sorted.length === 1 ? '' : 's'} from ${source} into shared/blocklist.ts`);
